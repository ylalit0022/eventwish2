/**
 * Get templates generated by a specific user (ObjectId)
 */
const getTemplatesByUser = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const { userId } = req.params;
        const { page = 1, limit = 20 } = req.query;
        
        if (!isValidObjectId(userId)) {
            return res.status(400).json(formatErrorResponse(
                'INVALID_USER_ID',
                'User ID must be a valid ObjectId',
                'userId',
                userId
            ));
        }
        
        const skip = (page - 1) * limit;
        
        const templates = await Template.find({ generatedByUser: userId })
            .select('title category isAIGenerated aiModel aiStyle aiPrompt createdAt')
            .skip(skip)
            .limit(parseInt(limit))
            .sort({ createdAt: -1 });
        
        const total = await Template.countDocuments({ generatedByUser: userId });
        
        // Get user info
        const user = await User.findById(userId).select('name email profileImage');
        
        logger.info(`Retrieved ${templates.length} templates generated by user: ${userId}`);
        
        return res.json(formatSuccessResponse({
            templates,
            user,
            pagination: {
                page: parseInt(page),
                limit: parseInt(limit),
                total,
                pages: Math.ceil(total / limit)
            },
            filter: { userId }
        }));
    });
};

