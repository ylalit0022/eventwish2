/**
 * Get AI generation statistics for a user
 */
const getUserGenerationStats = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const { userId } = req.params;
        
        if (!isValidObjectId(userId)) {
            return res.status(400).json(formatErrorResponse(
                'INVALID_USER_ID',
                'User ID must be a valid ObjectId',
                'userId',
                userId
            ));
        }
        
        const [
            totalGenerated,
            modelStats,
            styleStats,
            stageStats
        ] = await Promise.all([
            Template.countDocuments({ generatedByUser: userId, isAIGenerated: true }),
            Template.aggregate([
                { $match: { generatedByUser: userId, isAIGenerated: true, aiModel: { $ne: '' } } },
                { $group: { _id: '$aiModel', count: { $sum: 1 } } },
                { $sort: { count: -1 } }
            ]),
            Template.aggregate([
                { $match: { generatedByUser: userId, isAIGenerated: true, aiStyle: { $ne: '' } } },
                { $group: { _id: '$aiStyle', count: { $sum: 1 } } },
                { $sort: { count: -1 } }
            ]),
            Template.aggregate([
                { $match: { generatedByUser: userId, isAIGenerated: true } },
                { $group: { _id: '$aiGenerationStage', count: { $sum: 1 } } }
            ])
        ]);
        
        const user = await User.findById(userId).select('name email profileImage');
        
        logger.info(`Retrieved AI generation statistics for user: ${userId}`);
        
        return res.json(formatSuccessResponse({
            user,
            totalGenerated,
            modelStats,
            styleStats,
            stageStats,
            generatedAt: new Date().toISOString()
        }));
    });
};

