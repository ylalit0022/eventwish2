const Template = require('../../../models/Template');
const User = require('../../../models/User');
const { handleAsyncOperation, formatSuccessResponse, formatErrorResponse, isValidObjectId } = require('../../../utils/templateHelpers');
const logger = require('../../../utils/logger');

/**
 * AI Users Controller
 * Handles CRUD operations for AI user-related fields
 */

/**
 * Get AI user data for a template
 */
const getUserData = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const { templateId } = req.params;
        
        const template = await Template.findById(templateId)
            .select('generatedByUser generatedByUserUid')
            .populate('generatedByUser', 'name email profileImage');
        
        if (!template) {
            return res.status(404).json(formatErrorResponse(
                'TEMPLATE_NOT_FOUND',
                'Template not found',
                'templateId',
                templateId
            ));
        }
        
        logger.info(`Retrieved AI user data for template: ${templateId}`);
        
        return res.json(formatSuccessResponse({
            templateId: template._id,
            generatedByUser: template.generatedByUser,
            generatedByUserUid: template.generatedByUserUid
        }));
    });
};

/**
 * Update AI user data for a template
 */
const updateUserData = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const { templateId } = req.params;
        const { generatedByUser, generatedByUserUid } = req.body;
        
        const updateData = {};
        const modifiedFields = [];
        
        if (generatedByUser !== undefined) {
            if (generatedByUser && !isValidObjectId(generatedByUser)) {
                return res.status(400).json(formatErrorResponse(
                    'INVALID_USER_ID',
                    'Generated by user must be a valid ObjectId',
                    'generatedByUser',
                    generatedByUser
                ));
            }
            updateData.generatedByUser = generatedByUser;
            modifiedFields.push('generatedByUser');
        }
        
        if (generatedByUserUid !== undefined) {
            // Firebase UID validation
            if (generatedByUserUid && !/^[a-zA-Z0-9_-]{10,128}$/.test(generatedByUserUid)) {
                return res.status(400).json(formatErrorResponse(
                    'INVALID_FIREBASE_UID',
                    'Generated by user UID must be a valid Firebase UID',
                    'generatedByUserUid',
                    generatedByUserUid
                ));
            }
            updateData.generatedByUserUid = generatedByUserUid;
            modifiedFields.push('generatedByUserUid');
        }
        
        if (Object.keys(updateData).length === 0) {
            return res.status(400).json(formatErrorResponse(
                'NO_FIELDS_TO_UPDATE',
                'No valid fields provided for update'
            ));
        }
        
        const template = await Template.findByIdAndUpdate(
            templateId,
            { $set: updateData },
            { new: true, runValidators: true }
        ).select('generatedByUser generatedByUserUid').populate('generatedByUser', 'name email profileImage');
        
        if (!template) {
            return res.status(404).json(formatErrorResponse(
                'TEMPLATE_NOT_FOUND',
                'Template not found',
                'templateId',
                templateId
            ));
        }
        
        logger.info(`Updated AI user data for template: ${templateId}`, { modifiedFields });
        
        return res.json(formatSuccessResponse({
            templateId: template._id,
            generatedByUser: template.generatedByUser,
            generatedByUserUid: template.generatedByUserUid,
            modifiedFields
        }));
    });
};

