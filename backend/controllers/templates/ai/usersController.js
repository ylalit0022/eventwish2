/**
 * Batch assign generated-by-user for multiple templates
 */
const batchAssignUser = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const { templateIds, userId, uid } = req.body;
        
        if (!templateIds || !Array.isArray(templateIds) || templateIds.length === 0) {
            return res.status(400).json(formatErrorResponse(
                'INVALID_TEMPLATE_IDS',
                'Template IDs array is required'
            ));
        }
        
        const updateData = {};
        
        if (userId !== undefined) {
            if (userId && !isValidObjectId(userId)) {
                return res.status(400).json(formatErrorResponse(
                    'INVALID_USER_ID',
                    'User ID must be a valid ObjectId',
                    'userId',
                    userId
                ));
            }
            updateData.generatedByUser = userId;
        }
        
        if (uid !== undefined) {
            if (uid && !/^[a-zA-Z0-9_-]{10,128}$/.test(uid)) {
                return res.status(400).json(formatErrorResponse(
                    'INVALID_FIREBASE_UID',
                    'UID must be a valid Firebase UID',
                    'uid',
                    uid
                ));
            }
            updateData.generatedByUserUid = uid;
        }
        
        if (Object.keys(updateData).length === 0) {
            return res.status(400).json(formatErrorResponse(
                'NO_UPDATE_DATA',
                'Either userId or uid must be provided'
            ));
        }
        
        const result = await Template.updateMany(
            { _id: { $in: templateIds } },
            { $set: updateData },
            { runValidators: true }
        );
        
        logger.info(`Batch assigned user for ${result.modifiedCount} templates`);
        
        return res.json(formatSuccessResponse({
            message: 'Batch user assignment completed',
            matchedCount: result.matchedCount,
            modifiedCount: result.modifiedCount,
            templateIds,
            updateData
        }));
    });
};

/**
 * Get overall user generation statistics
 */
const getOverallUserStats = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const [
            totalUsersGenerated,
            topGeneratorsByObjectId,
            topGeneratorsByUid,
            totalAITemplates
        ] = await Promise.all([
            Template.distinct('generatedByUser', { isAIGenerated: true, generatedByUser: { $ne: null } }),
            Template.aggregate([
                { $match: { isAIGenerated: true, generatedByUser: { $ne: null } } },
                { $group: { _id: '$generatedByUser', count: { $sum: 1 } } },
                { $sort: { count: -1 } },
                { $limit: 10 },
                { 
                    $lookup: {
                        from: 'users',
                        localField: '_id',
                        foreignField: '_id',
                        as: 'user'
                    }
                },
                { $unwind: '$user' },
                {
                    $project: {
                        userId: '$_id',
                        count: 1,
                        userName: '$user.name',
                        userEmail: '$user.email'
                    }
                }
            ]),
            Template.aggregate([
                { $match: { isAIGenerated: true, generatedByUserUid: { $ne: null } } },
                { $group: { _id: '$generatedByUserUid', count: { $sum: 1 } } },
                { $sort: { count: -1 } },
                { $limit: 10 }
            ]),
            Template.countDocuments({ isAIGenerated: true })
        ]);
        
        logger.info('Retrieved overall user generation statistics');
        
        return res.json(formatSuccessResponse({
            totalUsersGenerated: totalUsersGenerated.length,
            totalAITemplates,
            topGeneratorsByObjectId,
            topGeneratorsByUid,
            generatedAt: new Date().toISOString()
        }));
    });
};

/**
 * Get top AI template generators
 */
const getTopGenerators = async (req, res) => {
    await handleAsyncOperation(res, async () => {
        const { limit = 10 } = req.params;
        const limitNum = parseInt(limit);
        
        if (isNaN(limitNum) || limitNum < 1 || limitNum > 100) {
            return res.status(400).json(formatErrorResponse(
                'INVALID_LIMIT',
                'Limit must be a number between 1 and 100',
                'limit',
                limit
            ));
        }
        
        const topGenerators = await Template.aggregate([
            { $match: { isAIGenerated: true, generatedByUser: { $ne: null } } },
            { $group: { _id: '$generatedByUser', count: { $sum: 1 } } },
            { $sort: { count: -1 } },
            { $limit: limitNum },
            { 
                $lookup: {
                    from: 'users',
                    localField: '_id',
                    foreignField: '_id',
                    as: 'user'
                }
            },
            { $unwind: '$user' },
            {
                $project: {
                    userId: '$_id',
                    count: 1,
                    userName: '$user.name',
                    userEmail: '$user.email',
                    userProfileImage: '$user.profileImage'
                }
            }
        ]);
        
        logger.info(`Retrieved top ${limitNum} AI template generators`);
        
        return res.json(formatSuccessResponse({
            topGenerators,
            limit: limitNum,
            generatedAt: new Date().toISOString()
        }));
    });
};

